export function familyCoverage(name) {
  return families.get(name) ??
    (/^(?:MSI Mystic Light (?:MS_|Common|[\dA-F]{4}:)|MSI Keyboard MS_|EVision Keyboard [\dA-F]{4}:|Thermaltake Riing(?: Trio| Quad)? \(PID )/.test(name) ? ['family'] : []);
}

